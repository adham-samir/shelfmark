export type MessageKey = keyof typeof ar;

const dictionaries: Record<Locale, Record<MessageKey, string>> = { ar, en };

export function translator(locale: Locale) {
  const dictionary = dictionaries[locale];
  return (key: MessageKey, vars?: Record<string, string | number>): string => {
    const template = dictionary[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in vars ? String(vars[name]) : match,
    );
  };
}

export type Translate = ReturnType<typeof translator>;

export const categories = ["phones", "headphones", "laptops", "accessories"] as const;

export function categoryLabel(t: Translate, value: string): string {
  const key = `category.${value}` as MessageKey;
  return dictionaries.ar[key] ? t(key) : value;
}

